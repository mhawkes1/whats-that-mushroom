/**
 * Drawings for answer options the words do not carry.
 *
 * Martin, using the app on 2026-10-29: "there should be images here to
 * help the user, as otherwise a user might not understand what domed or
 * coned is". He is right, and in this engine it is a safety question
 * rather than a nicety.
 *
 * A consistent answer never boosts; it only contradicts. So a user who
 * picks "Domed" when the cap is conical does not merely fail to help --
 * they push down every species that lists Conical. If one of those is
 * deadly, a guess has moved mass away from a lethal candidate. The
 * project already declined `Moderately spaced` as a gill-spacing option
 * for exactly this reason.
 *
 * `cap_shape` was the worst offender on presentation: six options under
 * twenty-five characters of guidance, "Photograph from the side." It is
 * not the worst on stakes -- no deadly species declares it -- and
 * `spore_print_colour` (9 deadly), `ring` (5) and `cap_surface` (5) are
 * the ones to illustrate next.
 *
 * **Drawings, never photographs.** A photograph of "a domed cap" is a
 * photograph of a species, and putting one beside an option teaches a
 * resemblance the taxonomy never claimed -- the same reason an empirical
 * confusion is never shown to a user as a lookalike.
 *
 * The PNGs are generated by `scripts/build_character_diagrams.py` from
 * SVGs in `docs/characters/`, rasterised by the same chromium pass the
 * app icons use. Never edit the PNGs; regenerate them. The requires are
 * static because the RN bundler resolves assets at build time, which is
 * also why an option with no drawing simply renders as it always did.
 */

type Art = Record<string, Record<string, number>>;

export const CHARACTER_ART: Art = {
  cap_shape: {
    Domed: require('../../assets/characters/cap-domed.png'),
    Flat: require('../../assets/characters/cap-flat.png'),
    'Funnel-shaped': require('../../assets/characters/cap-funnel-shaped.png'),
    Cylindrical: require('../../assets/characters/cap-cylindrical.png'),
    Conical: require('../../assets/characters/cap-conical.png'),
    Irregular: require('../../assets/characters/cap-irregular.png'),
  },
};

/** The drawing for one option, or undefined where there is none. */
export function artFor(characterKey: string, option: string): number | undefined {
  return CHARACTER_ART[characterKey]?.[option];
}
